#!/usr/bin/env bash
# Builds an Arch pacman package from an already-built tar.gz archive
# (packaging/scripts/archive.sh output).
#
# Usage: pacman/build.sh <tarball> <target-triple> <output-dir>
#
# Generates a PKGBUILD with the real crate version and the tarball's sha256,
# then runs `makepkg -f` in a staging directory. Requires makepkg (Arch and
# derivatives); not built in CI (ubuntu runners have no makepkg). The produced
# package is not installed here or anywhere; validation is structural via
# validate.sh. Re-running overwrites the output; safe to re-run.
set -euo pipefail

tarball=$1
triple=$2
out_dir=$3

[ -f "$tarball" ] || { echo "pacman/build.sh: no such tarball: $tarball" >&2; exit 1; }
command -v makepkg >/dev/null || {
    echo "pacman/build.sh: makepkg not available; pacman packages build on Arch only" >&2
    exit 1
}

repo=$(cd "$(dirname "$0")/../.." && pwd)
out_dir=$(mkdir -p "$out_dir" && cd "$out_dir" && pwd)
version=$(bash "$(dirname "$0")/../scripts/version.sh")
case $triple in
x86_64-unknown-linux-gnu) pkg_arch=x86_64 ;;
aarch64-unknown-linux-gnu) pkg_arch=aarch64 ;;
*) echo "pacman/build.sh: unsupported triple: $triple" >&2; exit 1 ;;
esac
# Arch pkgver forbids dashes.
pkgver=${version//-/.}
sum=$(sha256sum "$tarball" | cut -d' ' -f1)

# Never embed the caller-supplied tarball name in the generated PKGBUILD: a
# crafted filename could inject shell into it. The source entry always uses a
# canonical, script-derived name; the tarball is copied to that name.
canonical="nkeepass-${version}-${triple}.tar.gz"
if [ "$(basename "$tarball")" != "$canonical" ] && [ "$(basename "$tarball")" != "nkeepass-${pkgver}-${triple}.tar.gz" ]; then
    echo "pacman/build.sh: tarball must be named $canonical (got $(basename "$tarball"))" >&2
    exit 1
fi

stage=$(mktemp -d "${TMPDIR:-/tmp}/nkeepass-pacman.XXXXXX")
trap 'rm -rf "$stage"' EXIT

cat > "$stage/PKGBUILD" <<EOF
# Generated by packaging/pacman/build.sh from the crate version
# ${version}; do not edit by hand. Repackages the prebuilt release
# binary; it does not compile Rust. Not published to any repository.
pkgname=nkeepass
pkgver=${pkgver}
pkgrel=1
pkgdesc='Headless KeePass automation CLI and TUI'
arch=('${pkg_arch}')
url='https://github.com/neotales/neo-keepass'
license=('MIT')
provides=('nkeepass')
conflicts=('nkeepass')
options=('!debug' '!strip')
sha256sums=('${sum}')
source=('${canonical}')

package() {
    # makepkg runs package() inside \$srcdir after extracting the tarball,
    # which contains a single top-level directory named after the archive
    # holding the executable as nkp (the product's executable name; the
    # pacman package identifier itself stays nkeepass for compatibility).
    # !strip keeps the payload byte-identical to the tarball binary, which
    # validate.sh asserts by hash.
    local src="\$srcdir/nkeepass-${version}-${triple}"
    install -D -m 755 "\$src/nkp" "\${pkgdir}/usr/bin/nkp"
    install -D -m 644 "\$src/README.md" "\${pkgdir}/usr/share/doc/nkeepass/README.md"
    install -D -m 644 "\$src/LICENSE.md" "\${pkgdir}/usr/share/licenses/nkeepass/LICENSE"
}
EOF

# Copy under the canonical name; the source entry references only that name.
cp "$tarball" "$stage/$canonical"
(cd "$stage" && makepkg -f >/dev/null)
mv "$stage"/nkeepass-*.pkg.tar.* "$out_dir/"
echo "pacman/build.sh: wrote $out_dir/nkeepass-*.pkg.tar.* (pkgver ${pkgver}, arch ${pkg_arch})"
